CREATE OR REPLACE FUNCTION public.queryopt_validate_select(p_query text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_query text;
  v_match text[];
BEGIN
  v_query := regexp_replace(btrim(p_query), ';[[:space:]]*$', '');
  IF v_query IS NULL OR length(v_query) < 1 OR length(v_query) > 4000
     OR v_query !~* '^select[[:space:]]'
     OR v_query ~ '(;|--|/\*|\*/|\\|\$\$)'
     OR v_query ~* '\m(insert|update|delete|merge|drop|alter|create|truncate|grant|revoke|copy|call|do|execute|prepare|deallocate|vacuum|refresh|lock|set|reset|into|union|intersect|except)\M'
     OR v_query ~* '\m(select[[:space:]]+[^;]*\mfrom[[:space:]]*\()'
  THEN
    RAISE EXCEPTION 'Only one safe SELECT query is allowed.' USING ERRCODE = '22023';
  END IF;
  FOR v_match IN
    SELECT regexp_matches(v_query, '\m(from|join)[[:space:]]+([a-z_][a-z0-9_]*)', 'gi')
  LOOP
    IF lower(v_match[2]) NOT IN (
      'customers', 'products', 'orders', 'order_items', 'geolocation',
      'order_payments', 'order_reviews', 'sellers', 'product_category_name_translation'
    ) THEN
      RAISE EXCEPTION 'Queries can read only the Olist dataset tables.' USING ERRCODE = '22023';
    END IF;
  END LOOP;
  IF v_query !~* '\mfrom[[:space:]]+[a-z_][a-z0-9_]*' THEN
    RAISE EXCEPTION 'Query must read from an Olist table.' USING ERRCODE = '22023';
  END IF;
  RETURN v_query;
END;
$$;

DROP FUNCTION IF EXISTS public.begin_olist_import();
CREATE FUNCTION public.begin_olist_import(p_kind text, p_tables text[])
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_id uuid;
  v_active uuid;
  v_any_rows boolean;
  v_has_dataset boolean;
  v_table text;
  v_count bigint;
  v_allowed_supplemental text[] := ARRAY[
    'order_payments', 'order_reviews', 'sellers',
    'product_category_name_translation', 'geolocation'
  ];
BEGIN
  PERFORM public.queryopt_assert_service_role();
  PERFORM pg_advisory_xact_lock(hashtext('queryopt-olist-import'));
  IF p_kind NOT IN ('core', 'supplemental') OR cardinality(p_tables) < 1 THEN
    RAISE EXCEPTION 'Dataset import request is invalid.' USING ERRCODE = '22023';
  END IF;

  SELECT id INTO v_active FROM public.dataset_imports
    WHERE status = 'uploading' AND kind = p_kind AND selected_tables = p_tables
    ORDER BY created_at DESC LIMIT 1;
  IF v_active IS NOT NULL THEN RETURN v_active; END IF;
  IF EXISTS (SELECT 1 FROM public.dataset_imports WHERE status = 'uploading') THEN
    RAISE EXCEPTION 'Another dataset import is still in progress.' USING ERRCODE = '23505';
  END IF;

  SELECT EXISTS (SELECT 1 FROM public.app_meta WHERE key = 'dataset_uploaded_at') INTO v_has_dataset;
  SELECT (SELECT count(*) > 0 FROM public.customers)
      OR (SELECT count(*) > 0 FROM public.products)
      OR (SELECT count(*) > 0 FROM public.orders)
      OR (SELECT count(*) > 0 FROM public.order_items)
    INTO v_any_rows;
  IF p_kind = 'core' THEN
    IF p_tables <> ARRAY['customers', 'orders', 'order_items', 'products']::text[] THEN
      RAISE EXCEPTION 'The first import must include all four core Olist tables.' USING ERRCODE = '22023';
    END IF;
    IF v_has_dataset THEN RAISE EXCEPTION 'The core Olist dataset is already loaded.' USING ERRCODE = '23505'; END IF;
    IF v_any_rows THEN RAISE EXCEPTION 'The database contains a partial core import. Resume its active upload.' USING ERRCODE = '23505'; END IF;
  ELSE
    IF NOT v_has_dataset THEN RAISE EXCEPTION 'Upload the four core Olist tables first.' USING ERRCODE = '22023'; END IF;
    IF NOT (p_tables <@ v_allowed_supplemental) THEN
      RAISE EXCEPTION 'Only the five supplemental Olist tables can be added.' USING ERRCODE = '22023';
    END IF;
    FOREACH v_table IN ARRAY p_tables LOOP
      IF v_table <> ALL (v_allowed_supplemental) THEN
        RAISE EXCEPTION 'Only the five supplemental Olist tables can be added.' USING ERRCODE = '22023';
      END IF;
      EXECUTE format('SELECT count(*) FROM public.%I', v_table) INTO v_count;
      IF v_count > 0 THEN RAISE EXCEPTION 'Olist table % is already loaded.', v_table USING ERRCODE = '23505'; END IF;
    END LOOP;
  END IF;

  INSERT INTO public.dataset_imports(status, kind, selected_tables)
    VALUES ('uploading', p_kind, p_tables) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.finish_olist_import(p_import_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_kind text;
  v_selected text[];
  v_sizes jsonb;
  v_now timestamptz := now();
  v_table text;
  v_count bigint;
BEGIN
  PERFORM public.queryopt_assert_service_role();
  PERFORM pg_advisory_xact_lock(hashtext('queryopt-olist-import'));
  SELECT kind, selected_tables INTO v_kind, v_selected FROM public.dataset_imports
    WHERE id = p_import_id AND status = 'uploading';
  IF v_kind IS NULL THEN RAISE EXCEPTION 'Dataset import was not active.' USING ERRCODE = '22023'; END IF;

  FOREACH v_table IN ARRAY v_selected LOOP
    EXECUTE format('SELECT count(*) FROM public.%I', v_table) INTO v_count;
    IF v_count = 0 THEN RAISE EXCEPTION 'Table % is empty; finish after all selected files upload.', v_table USING ERRCODE = '22023'; END IF;
  END LOOP;
  IF v_kind = 'core' AND (
    (SELECT count(*) FROM public.customers) = 0 OR (SELECT count(*) FROM public.products) = 0
    OR (SELECT count(*) FROM public.orders) = 0 OR (SELECT count(*) FROM public.order_items) = 0
  ) THEN
    RAISE EXCEPTION 'All four core Olist tables must have rows before finishing.' USING ERRCODE = '22023';
  END IF;

  SELECT jsonb_build_object(
    'customers', (SELECT count(*) FROM public.customers),
    'products', (SELECT count(*) FROM public.products),
    'orders', (SELECT count(*) FROM public.orders),
    'order_items', (SELECT count(*) FROM public.order_items),
    'order_payments', (SELECT count(*) FROM public.order_payments),
    'order_reviews', (SELECT count(*) FROM public.order_reviews),
    'sellers', (SELECT count(*) FROM public.sellers),
    'product_category_name_translation', (SELECT count(*) FROM public.product_category_name_translation),
    'geolocation', (SELECT count(*) FROM public.geolocation)
  ) INTO v_sizes;
  UPDATE public.dataset_imports SET status = 'complete', completed_at = v_now, table_sizes = v_sizes
    WHERE id = p_import_id AND status = 'uploading';
  INSERT INTO public.app_meta(key, value) VALUES
    ('dataset_name', 'Brazilian E-Commerce Public Dataset by Olist'),
    ('dataset_license', 'CC BY-NC-SA 4.0'),
    ('dataset_source', 'https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce'),
    ('dataset_last_updated_at', v_now::text)
  ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
  IF v_kind = 'core' THEN
    INSERT INTO public.app_meta(key, value) VALUES ('dataset_uploaded_at', v_now::text)
      ON CONFLICT (key) DO NOTHING;
  END IF;
  PERFORM setval(pg_get_serial_sequence('public.geolocation', 'geolocation_id'),
    GREATEST(COALESCE((SELECT max(geolocation_id) FROM public.geolocation), 1), 1),
    EXISTS (SELECT 1 FROM public.geolocation));
  RETURN jsonb_build_object('dataset_name', 'Brazilian E-Commerce Public Dataset by Olist', 'uploaded_at', COALESCE((SELECT value FROM public.app_meta WHERE key = 'dataset_uploaded_at'), v_now::text), 'table_sizes', v_sizes);
END;
$$;

