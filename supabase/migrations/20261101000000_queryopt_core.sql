CREATE OR REPLACE FUNCTION public.queryopt_assert_service_role()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_role text;
BEGIN
  v_role := COALESCE(
    NULLIF(current_setting('request.jwt.claim.role', true), ''),
    (COALESCE(NULLIF(current_setting('request.jwt.claims', true), ''), '{}')::jsonb ->> 'role'),
    ''
  );
  IF v_role <> 'service_role' THEN
    RAISE EXCEPTION 'service role required' USING ERRCODE = '42501';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.queryopt_validate_select(p_query text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_query text;
  v_match text[];
BEGIN
  v_query := btrim(p_query);
  v_query := regexp_replace(v_query, ';[[:space:]]*$', '');
  IF v_query IS NULL OR length(v_query) < 1 OR length(v_query) > 4000
     OR v_query !~* '^select[[:space:]]'
     OR v_query ~ '(;|--|/\*|\*/|\\|\$\$)'
     OR v_query ~* '\m(insert|update|delete|merge|drop|alter|create|truncate|grant|revoke|copy|call|do|execute|prepare|deallocate|vacuum|refresh|lock|set|reset|into|union|intersect|except)\M'
     OR v_query ~* '\m(select[[:space:]]+[^;]*\mfrom[[:space:]]*\()'
  THEN
    RAISE EXCEPTION 'Only one safe SELECT query is allowed.' USING ERRCODE = '22023';
  END IF;

  FOR v_match IN
    SELECT regexp_matches(v_query, '\m(from|join)[[:space:]]+([a-z_][a-z0-9_]*)', 'gi')
  LOOP
    IF lower(v_match[2]) NOT IN ('customers', 'products', 'orders', 'order_items') THEN
      RAISE EXCEPTION 'Queries can read only the four Olist tables.' USING ERRCODE = '22023';
    END IF;
  END LOOP;
  IF v_query !~* '\mfrom[[:space:]]+[a-z_][a-z0-9_]*' THEN
    RAISE EXCEPTION 'Query must read from an Olist table.' USING ERRCODE = '22023';
  END IF;
  RETURN v_query;
END;
$$;

CREATE OR REPLACE FUNCTION public.begin_olist_import()
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_id uuid;
  v_active uuid;
  v_sizes jsonb;
BEGIN
  PERFORM public.queryopt_assert_service_role();
  PERFORM pg_advisory_xact_lock(hashtext('queryopt-olist-import'));

  IF EXISTS (SELECT 1 FROM public.app_meta WHERE key = 'dataset_uploaded_at') THEN
    RAISE EXCEPTION 'An Olist dataset is already loaded.' USING ERRCODE = '23505';
  END IF;

  SELECT id INTO v_active FROM public.dataset_imports
    WHERE status = 'uploading' AND created_at > now() - interval '12 hours'
    ORDER BY created_at DESC LIMIT 1;
  IF v_active IS NOT NULL THEN
    RETURN v_active;
  END IF;

  SELECT jsonb_build_object(
    'customers', (SELECT count(*) FROM public.customers),
    'products', (SELECT count(*) FROM public.products),
    'orders', (SELECT count(*) FROM public.orders),
    'order_items', (SELECT count(*) FROM public.order_items)
  ) INTO v_sizes;
  IF EXISTS (SELECT 1 FROM jsonb_each_text(v_sizes) WHERE value::bigint > 0) THEN
    RAISE EXCEPTION 'The database contains incomplete dataset rows. Finish the current import before starting a new one.' USING ERRCODE = '23505';
  END IF;

  INSERT INTO public.dataset_imports(status) VALUES ('uploading') RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.finish_olist_import(p_import_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_sizes jsonb;
  v_now timestamptz := now();
BEGIN
  PERFORM public.queryopt_assert_service_role();
  PERFORM pg_advisory_xact_lock(hashtext('queryopt-olist-import'));
  SELECT jsonb_build_object(
    'customers', (SELECT count(*) FROM public.customers),
    'products', (SELECT count(*) FROM public.products),
    'orders', (SELECT count(*) FROM public.orders),
    'order_items', (SELECT count(*) FROM public.order_items)
  ) INTO v_sizes;
  IF EXISTS (SELECT 1 FROM jsonb_each_text(v_sizes) WHERE value::bigint = 0) THEN
    RAISE EXCEPTION 'All four Olist tables must have rows before finishing the import.' USING ERRCODE = '22023';
  END IF;

  UPDATE public.dataset_imports SET status = 'complete', completed_at = v_now, table_sizes = v_sizes
    WHERE id = p_import_id AND status = 'uploading';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Dataset import was not active.' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.app_meta(key, value) VALUES
    ('dataset_name', 'Brazilian E-Commerce Public Dataset by Olist'),
    ('dataset_uploaded_at', v_now::text),
    ('dataset_license', 'CC BY-NC-SA 4.0'),
    ('dataset_source', 'https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce')
  ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
  RETURN jsonb_build_object('dataset_name', 'Brazilian E-Commerce Public Dataset by Olist', 'uploaded_at', v_now, 'table_sizes', v_sizes);
END;
$$;

