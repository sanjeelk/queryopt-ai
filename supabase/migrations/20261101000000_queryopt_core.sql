-- QueryOpt AI: Supabase-backed Olist storage and protected plan-execution RPCs.
-- Tables stay private to the service role; browser traffic is routed through the Edge Function.

CREATE TABLE IF NOT EXISTS public.app_meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.customers (
  customer_id text PRIMARY KEY,
  customer_unique_id text NOT NULL,
  customer_zip_code_prefix integer,
  customer_city text,
  customer_state text
);
CREATE INDEX IF NOT EXISTS customers_state_idx ON public.customers (customer_state);
CREATE INDEX IF NOT EXISTS customers_city_idx ON public.customers (customer_city);

CREATE TABLE IF NOT EXISTS public.products (
  product_id text PRIMARY KEY,
  product_category_name text,
  product_name_lenght integer,
  product_description_lenght integer,
  product_photos_qty integer,
  product_weight_g double precision,
  product_length_cm double precision,
  product_height_cm double precision,
  product_width_cm double precision
);
CREATE INDEX IF NOT EXISTS products_category_idx ON public.products (product_category_name);

CREATE TABLE IF NOT EXISTS public.orders (
  order_id text PRIMARY KEY,
  customer_id text NOT NULL,
  order_status text NOT NULL,
  order_purchase_timestamp timestamp,
  order_approved_at timestamp,
  order_delivered_carrier_date timestamp,
  order_delivered_customer_date timestamp,
  order_estimated_delivery_date timestamp
);
CREATE INDEX IF NOT EXISTS orders_customer_idx ON public.orders (customer_id);
CREATE INDEX IF NOT EXISTS orders_purchase_idx ON public.orders (order_purchase_timestamp);
CREATE INDEX IF NOT EXISTS orders_status_idx ON public.orders (order_status);

CREATE TABLE IF NOT EXISTS public.order_items (
  order_id text NOT NULL,
  order_item_id integer NOT NULL,
  product_id text NOT NULL,
  seller_id text NOT NULL,
  shipping_limit_date timestamp,
  price double precision NOT NULL,
  freight_value double precision NOT NULL,
  PRIMARY KEY (order_id, order_item_id)
);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON public.order_items (order_id);
CREATE INDEX IF NOT EXISTS order_items_product_idx ON public.order_items (product_id);
CREATE INDEX IF NOT EXISTS order_items_seller_idx ON public.order_items (seller_id);

CREATE TABLE IF NOT EXISTS public.query_measurements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query_key text NOT NULL,
  run_id uuid NOT NULL,
  query_text text NOT NULL,
  strategy text NOT NULL,
  execution_ms double precision NOT NULL,
  estimated_cost double precision NOT NULL,
  actual_rows bigint NOT NULL,
  predicted_ms double precision,
  shared_hit_blocks bigint NOT NULL DEFAULT 0,
  shared_read_blocks bigint NOT NULL DEFAULT 0,
  plan_json jsonb NOT NULL,
  is_benchmark boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS query_measurements_key_idx ON public.query_measurements (query_key);
CREATE INDEX IF NOT EXISTS query_measurements_run_idx ON public.query_measurements (run_id);
CREATE INDEX IF NOT EXISTS query_measurements_strategy_idx ON public.query_measurements (strategy);
CREATE INDEX IF NOT EXISTS query_measurements_created_idx ON public.query_measurements (created_at DESC);

CREATE TABLE IF NOT EXISTS public.dataset_imports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  status text NOT NULL CHECK (status IN ('uploading', 'complete', 'failed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  table_sizes jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE UNIQUE INDEX IF NOT EXISTS dataset_one_active_import_idx
  ON public.dataset_imports ((status)) WHERE status = 'uploading';

