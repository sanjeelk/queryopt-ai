$$;

CREATE OR REPLACE FUNCTION public.run_explain(p_query text, p_strategy text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_query text;
  v_explain jsonb;
  v_plan jsonb;
  v_settings jsonb;
BEGIN
  PERFORM public.queryopt_assert_service_role();
  v_query := public.queryopt_validate_select(p_query);
  IF p_strategy NOT IN ('planner_default', 'index_friendly', 'join_friendly', 'parallel_friendly') THEN
    RAISE EXCEPTION 'Unknown planner strategy.' USING ERRCODE = '22023';
  END IF;

  PERFORM set_config('statement_timeout', '2500', true);
  PERFORM set_config('lock_timeout', '500', true);
  IF p_strategy = 'index_friendly' THEN
    PERFORM set_config('enable_seqscan', 'off', true);
  ELSIF p_strategy = 'join_friendly' THEN
    PERFORM set_config('enable_nestloop', 'off', true);
  ELSIF p_strategy = 'parallel_friendly' THEN
    PERFORM set_config('max_parallel_workers_per_gather', '2', true);
  END IF;

  EXECUTE format('EXPLAIN (ANALYZE TRUE, BUFFERS TRUE, FORMAT JSON) %s', v_query) INTO v_explain;
  v_plan := v_explain -> 0 -> 'Plan';
  RETURN jsonb_build_object(
    'strategy', p_strategy,
    'planning_ms', COALESCE((v_explain -> 0 ->> 'Planning Time')::double precision, 0),
    'execution_ms', COALESCE((v_explain -> 0 ->> 'Execution Time')::double precision, 0),
    'estimated_cost', COALESCE((v_plan ->> 'Total Cost')::double precision, 0),
    'actual_rows', COALESCE((v_plan ->> 'Actual Rows')::bigint, 0),
    'shared_hit_blocks', COALESCE((v_plan ->> 'Shared Hit Blocks')::bigint, 0),
    'shared_read_blocks', COALESCE((v_plan ->> 'Shared Read Blocks')::bigint, 0),
    'plan_json', v_explain -> 0
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.preview_olist_query(p_query text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_query text;
  v_rows jsonb;
BEGIN
  PERFORM public.queryopt_assert_service_role();
  v_query := public.queryopt_validate_select(p_query);
  PERFORM set_config('statement_timeout', '1800', true);
  EXECUTE format(
    'SELECT COALESCE(jsonb_agg(to_jsonb(q)), ''[]''::jsonb) FROM (SELECT * FROM (%s) AS source LIMIT 12) AS q',
    v_query
  ) INTO v_rows;
  RETURN COALESCE(v_rows, '[]'::jsonb);
END;
$$;

